export type AdviceStats = {
  currentWeight: number;
  targetWeight: number;
  trend: number;
  waterGlasses: number;
  mealsDone: number;
  mealsTotal: number;
  exerciseDone: number;
  exerciseTotal: number;
  tasksDone: number;
  tasksTotal: number;
};

export function getAdvice(language: Language, stats: AdviceStats) {
  const progress = stats.currentWeight <= stats.targetWeight;
  const mealProgress = stats.mealsDone / Math.max(stats.mealsTotal, 1);
  const taskProgress = stats.tasksDone / Math.max(stats.tasksTotal, 1);
  if (stats.waterGlasses < 4) {
    return language === 'fr' ? 'Bois un verre maintenant, puis un autre après ton prochain repas.' : language === 'ar' ? 'اشرب كوباً الآن ثم كوباً آخر بعد وجبتك القادمة.' : 'Have one glass now, then another after your next meal.';
  }
  if (stats.exerciseDone === 0) {
    return language === 'fr' ? 'Une courte marche ou quelques étirements seraient un bon prochain pas, sans pression.' : language === 'ar' ? 'مشي قصير أو بعض التمدد سيكون خطوة تالية جيدة، دون ضغط.' : 'A short walk or a few stretches would be a good next step, without pressure.';
  }
  if (stats.trend > 0 && !progress) {
    return language === 'fr' ? 'La tendance monte un peu. Garde des portions régulières et reviens à une routine simple demain.' : language === 'ar' ? 'الاتجاه يرتفع قليلاً. حافظ على حصص منتظمة وعد إلى روتين بسيط غداً.' : 'The trend is slightly up. Keep portions steady and return to a simple routine tomorrow.';
  }
  if (mealProgress < 0.5) {
    return language === 'fr' ? 'Un repas équilibré de plus t’aidera à garder ton énergie stable aujourd’hui.' : language === 'ar' ? 'وجبة متوازنة إضافية ستساعدك على الحفاظ على طاقتك اليوم.' : 'One more balanced meal will help keep your energy steady today.';
  }
  if (taskProgress >= 0.8) {
    return language === 'fr' ? 'Ta journée est bien engagée. Termine doucement et prépare une soirée reposante.' : language === 'ar' ? 'يومك يسير بشكل جيد. أنهِه بهدوء واستعد لمساء مريح.' : 'Your day is on track. Finish gently and make space for a restful evening.';
  }
  return language === 'fr' ? 'La régularité compte plus que la perfection. Continue avec le prochain petit pas.' : language === 'ar' ? 'الاستمرارية أهم من الكمال. واصل بالخطوة الصغيرة التالية.' : 'Consistency matters more than perfection. Keep going with the next small step.';
}